fn main() {
    use cmake::Config;
    use std::env;
    use std::path::PathBuf;

    let dst = Config::new("./")
        .define("BUILD_TESTING", "OFF")
        .define("CMAKE_C_COMPILER_WORKS", "1")
        .define("CMAKE_CXX_COMPILER_WORKS", "1")
        .pic(false)
        .build();

    println!("cargo:rustc-link-search=native={}/lib", dst.display());
    println!("cargo:rustc-link-lib=static=smtc-modem-cores");

    let bindings = bindgen::Builder::default()
        .raw_line("use cty;")
        .use_core()
        .ctypes_prefix("cty")
        .detect_include_paths(true)
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/sx126x_driver/src/sx126x.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/sx126x_driver/src/sx126x_hal.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_radio.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_system.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_regmem.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_lr_fhss.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_gnss.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_rttof.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/lr11xx_driver/src/lr11xx_hal.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/sx127x_driver/src/sx127x.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/sx127x_driver/src/sx127x_hal.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/sx128x_driver/src/sx128x.h")
        .header("SWL2001/lbm_lib/smtc_modem_core/radio_drivers/sx128x_driver/src/sx128x_hal.h")
        .clang_arg(format!("-I{}/include", dst.display()))
        // sx127x_t layout depends on these (keep in sync with CMakeLists)
        .clang_arg("-DSX1272")
        .clang_arg("-DSX1276")
        .trust_clang_mangling(false)
        // sx127x: allowlist by pattern like lr11xx
        .allowlist_function("sx127x_.*")
        .allowlist_type("sx127x_.*")
        .rustified_enum("sx127x_status_e")
        .rustified_enum("sx127x_hal_status_e")
        .rustified_enum("sx127x_radio_id_e")
        // sx128x: allowlist by pattern like lr11xx
        .allowlist_function("sx128x_.*")
        .allowlist_type("sx128x_.*")
        .rustified_enum("sx128x_.*_e")
        // lr11xx: unlike the function-by-function sx126x list below, the
        // whole radio-core surface is allowlisted by pattern
        .allowlist_function("lr11xx_(radio|system|regmem|lr_fhss|gnss|rttof)_.*")
        // buffer sizes and bit masks (e.g. single-almanac read/write sizes)
        .allowlist_var("LR11XX_GNSS_.*")
        .allowlist_var("LR11XX_RTTOF_.*")
        .allowlist_type("lr11xx_.*")
        .rustified_enum("lr11xx_.*_e")
        .derive_default(true)
        .allowlist_type("sx126x_status_e")
        .rustified_enum("sx126x_status_e")
        .allowlist_type("sx126x_hal_status_e")
        .rustified_enum("sx126x_hal_status_e")
        .allowlist_type("sx126x_sleep_cfgs_e")
        .rustified_enum("sx126x_sleep_cfgs_e")
        .allowlist_type("sx126x_standby_cfgs_e")
        .rustified_enum("sx126x_standby_cfgs_e")
        .allowlist_type("sx126x_lora_sf_e")
        .rustified_enum("sx126x_lora_sf_e")
        .allowlist_type("sx126x_lora_bw_e")
        .rustified_enum("sx126x_lora_bw_e")
        .allowlist_type("sx126x_lora_cr_e")
        .rustified_enum("sx126x_lora_cr_e")
        .allowlist_type("sx126x_lora_pkt_len_modes_e")
        .rustified_enum("sx126x_lora_pkt_len_modes_e")
        .allowlist_type("sx126x_mod_params_lora_s")
        .allowlist_type("sx126x_pkt_params_lora_s")
        .allowlist_function("sx126x_set_sleep")
        .allowlist_function("sx126x_set_standby")
        .allowlist_function("sx126x_set_rf_freq")
        .allowlist_function("sx126x_set_lora_mod_params")
        .allowlist_function("sx126x_set_lora_pkt_params")
        .allowlist_function("sx126x_set_lora_sync_word")
        .allowlist_function("sx126x_set_buffer_base_address")
        .allowlist_function("sx126x_write_buffer")
        .allowlist_function("sx126x_set_tx")
        .allowlist_function("sx126x_set_dio_irq_params")
        .allowlist_function("sx126x_clear_irq_status")
        .allowlist_type("sx126x_cad_symbs_e")
        .rustified_enum("sx126x_cad_symbs_e")
        .allowlist_type("sx126x_cad_exit_modes_e")
        .rustified_enum("sx126x_cad_exit_modes_e")
        .allowlist_type("sx126x_cad_param_s")
        .allowlist_function("sx126x_stop_timer_on_preamble")
        .allowlist_function("sx126x_set_lora_symb_nb_timeout")
        .allowlist_function("sx126x_cfg_rx_boosted")
        .allowlist_function("sx126x_set_rx_with_timeout_in_rtc_step")
        .allowlist_function("sx126x_set_cad_params")
        .allowlist_function("sx126x_set_cad")
        .allowlist_type("sx126x_chip_status_s")
        .allowlist_type("sx126x_rx_buffer_status_s")
        .allowlist_type("sx126x_pkt_status_lora_s")
        .allowlist_function("sx126x_get_status")
        .allowlist_function("sx126x_get_rx_buffer_status")
        .allowlist_function("sx126x_read_buffer")
        .allowlist_function("sx126x_get_lora_pkt_status")
        .allowlist_function("sx126x_get_rssi_inst")
        .allowlist_function("sx126x_get_irq_status")
        .allowlist_function("sx126x_cal_img")
        .allowlist_function("sx126x_cal_img_in_mhz")
        .allowlist_function("sx126x_set_tx_cw")
        .allowlist_type("sx126x_pa_cfg_params_s")
        .allowlist_type("sx126x_ramp_time_e")
        .rustified_enum("sx126x_ramp_time_e")
        .allowlist_function("sx126x_set_pa_cfg")
        .allowlist_function("sx126x_set_tx_params")
        .allowlist_function("sx126x_cfg_tx_clamp")
        .allowlist_function("sx126x_set_pkt_type")
        .allowlist_type("sx126x_pkt_types_e")
        .rustified_enum("sx126x_pkt_types_e")
        .allowlist_function("sx126x_set_dio2_as_rf_sw_ctrl")
        .allowlist_function("sx126x_add_registers_to_retention_list")
        .generate()
        .expect("Failed to generate sx12xx bindings!");

    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap());
    bindings
        .write_to_file(out_path.join("smtc-modem-cores.rs"))
        .expect("Couldn't write bindings!");
}
